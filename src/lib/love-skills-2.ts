// The reader and existing widget exporter both use data/love-skills-2/content.
export function readLoveSkills2() {
  const dir = path.join(process.cwd(), "data", LOVE_SKILLS_2.id, "content");
  return fs.readdirSync(dir).filter(name => name.endsWith(".md")).sort().map((name, index) => {
    const md = fs.readFileSync(path.join(dir, name), "utf8");
    const title = md.match(/^#\s+(.+)$/m)?.[1] ?? name;
    const body = md.replace(/^#\s+.+\r?\n/, "");
    return { id: `ls2-section-${index}`, title, html: marked.parse(body.replace(/~/g, "&#126;"), { async: false }) as string };
  });
}

